func main() {
	root := "."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	generate(root)
}

func generate(root string) {
	g := generator{definitions: make(map[string]definition)}
	for _, pkg := range []string{"world", "worldlightmap", "worldmaterial", "worldparticles"} {
		files, err := filepath.Glob(filepath.Join(root, "format", pkg, "*.go"))
		must(err)
		for _, path := range files {
			if strings.HasSuffix(path, "_test.go") || strings.HasSuffix(path, ".generated.go") {
				continue
			}
			file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
			must(err)
			for _, decl := range file.Decls {
				if group, ok := decl.(*ast.GenDecl); ok && group.Tok == token.TYPE {
					for _, spec := range group.Specs {
						t := spec.(*ast.TypeSpec)
						g.definitions[pkg+"."+t.Name.Name] = definition{pkg, t.Name.Name, t.Type}
					}
				}
			}
		}
	}
	for _, config := range []struct {
		pkg   string
		roots []string
	}{{"world", []string{"Document", "SolidRenderers"}}, {"worldlightmap", []string{"Layout", "PrebakeManifest", "EnvironmentVariants", "world.Vec2", "world.Plane", "world.PointLight"}}, {"worldmaterial", []string{"Layout"}}, {"worldparticles", []string{"Document"}}} {
		g.current = config.pkg
		g.needed = make(map[string]bool)
		for _, root := range config.roots {
			if strings.Contains(root, ".") {
				g.require(root)
			} else {
				g.require(config.pkg + "." + root)
			}
		}
		keys := make([]string, 0, len(g.needed))
		for key := range g.needed {
			keys = append(keys, key)
		}
		slices.Sort(keys)
		var output bytes.Buffer
		fmt.Fprintf(
			&output,
			"// Code generated by internal/codegen/binary; DO NOT EDIT.\npackage %s\n\nimport (\n\"github.com/karty-game/karty-sdk/internal/binwire\"\n",
			config.pkg,
		)
		if config.pkg != "world" && g.needed["world.Vec3"] {
			fmt.Fprintln(&output, "\"github.com/karty-game/karty-sdk/format/world\"")
		}
		fmt.Fprintln(&output, ")")
		for _, key := range keys {
			d := g.definitions[key]
			name := methodName(d)
			typ := g.typeName(d)
			fmt.Fprintf(&output, "func write%s(w *binwire.Writer,v *%s){\nif w.Err()!=nil {return}\n", name, typ)
			g.emit(&output, d.pkg, d.expr, "(*v)", key, "write")
			fmt.Fprintln(&output, "}")
			fmt.Fprintf(&output, "func read%s(r *binwire.Reader,v *%s){\n", name, typ)
			g.emit(&output, d.pkg, d.expr, "(*v)", key, "read")
			fmt.Fprintln(&output, "}")
			fmt.Fprintf(&output, "func scan%s(r *binwire.Reader){\n", name)
			g.emit(&output, d.pkg, d.expr, "", key, "scan")
			fmt.Fprintln(&output, "}")
		}
		formatted, err := format.Source(output.Bytes())
		if err != nil {
			os.Stderr.Write(output.Bytes())
			must(err)
		}
		must(os.WriteFile(filepath.Join(root, "format", config.pkg, "binary.generated.go"), formatted, 0o600))
	}
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
func primitive(name string) bool {
	return slices.Contains([]string{"bool", "string", "int", "uint8", "uint16", "uint32", "uint64", "int32", "float32", "float64"}, name)
}
func (g *generator) named(pkg string, expr ast.Expr) (definition, bool) {
	switch t := expr.(type) {
	case *ast.Ident:
		if !primitive(t.Name) {
			d, ok := g.definitions[pkg+"."+t.Name]
			return d, ok
		}
	case *ast.SelectorExpr:
		alias := t.X.(*ast.Ident).Name
		d, ok := g.definitions[alias+"."+t.Sel.Name]
		return d, ok
	}
	return definition{}, false
}
func (g *generator) require(key string) {
	if g.needed[key] {
		return
	}
	g.needed[key] = true
	d, ok := g.definitions[key]
	if !ok {
		panic(key)
	}
	g.walk(d.pkg, d.expr)
}
func (g *generator) walk(pkg string, expr ast.Expr) {
	if d, ok := g.named(pkg, expr); ok {
		g.require(d.pkg + "." + d.name)
		return
	}
	switch t := expr.(type) {
	case *ast.StructType:
		for _, f := range t.Fields.List {
			g.walk(pkg, f.Type)
		}
	case *ast.ArrayType:
		g.walk(pkg, t.Elt)
	case *ast.StarExpr:
		g.walk(pkg, t.X)
	case *ast.Ident:
		if !primitive(t.Name) {
			panic(t.Name)
		}
	default:
		panic(fmt.Sprintf("unsupported %T", expr))
	}
}
func methodName(d definition) string { return strings.ToUpper(d.pkg[:1]) + d.pkg[1:] + d.name }
func (g *generator) typeName(d definition) string {
	if d.pkg == g.current {
		return d.name
	}
	return d.pkg + "." + d.name
}
func (g *generator) exprName(pkg string, expr ast.Expr) string {
	if d, ok := g.named(pkg, expr); ok {
		return g.typeName(d)
	}
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return "*" + g.exprName(pkg, t.X)
	case *ast.ArrayType:
		if t.Len == nil {
			return "[]" + g.exprName(pkg, t.Elt)
		}
		return "[" + t.Len.(*ast.BasicLit).Value + "]" + g.exprName(pkg, t.Elt)
	}
	panic("type")
}
func (g *generator) dimensions(pkg string, expr ast.Expr) (int, int) {
	if d, ok := g.named(pkg, expr); ok {
		return g.dimensions(d.pkg, d.expr)
	}
	switch t := expr.(type) {
	case *ast.Ident:
		switch t.Name {
		case "bool", "uint8":
			return 1, 1
		case "uint16":
			return 2, 2
		case "int", "int32", "uint32", "float32":
			if t.Name == "int" {
				return 4, 8
			}
			return 4, 4
		case "uint64", "float64":
			return 8, 8
		case "string":
			return 4, 16
		}
	case *ast.StarExpr:
		return 1, 8
	case *ast.ArrayType:
		if t.Len == nil {
			return 4, 24
		}
		n, _ := strconv.Atoi(t.Len.(*ast.BasicLit).Value)
		minimum, size := g.dimensions(pkg, t.Elt)
		return n * minimum, n * size
	case *ast.StructType:
		minimum, size := 0, 0
		for _, f := range t.Fields.List {
			a, b := g.dimensions(pkg, f.Type)
			minimum += a * len(f.Names)
			size += ((b + 7) / 8 * 8) * len(f.Names)
		}
		return minimum, size
	}
	panic("dimensions")
}
func (g *generator) next() string { g.serial++; return fmt.Sprintf("i%d", g.serial) }
func (g *generator) emit(out *bytes.Buffer, pkg string, expr ast.Expr, value, key, mode string) {
	if d, ok := g.named(pkg, expr); ok {
		prefix := "scan"
		arg := "r"
		if mode == "write" {
			prefix = "write"
			arg = "w,&" + value
		} else if mode == "read" {
			prefix = "read"
			arg = "r,&" + value
		}
		fmt.Fprintf(out, "%s%s(%s)\n", prefix, methodName(d), arg)
		return
	}
	switch t := expr.(type) {
	case *ast.StructType:
		for _, field := range t.Fields.List {
			for _, name := range field.Names {
				fieldKey := key + "." + name.Name
				// KWR2 appends its separately generated extension after the frozen base.
				if fieldKey == "world.Document.SolidRenderers" || fieldKey == "world.Environment.Backdrop" {
					continue
				}
				// Revision-1/2 prebake manifests retain their exact bytes. Only
				// recognized bounded producers append their typed ray distance.
				if fieldKey == "worldlightmap.PrebakeManifest.Producer" && mode == "scan" {
					fmt.Fprintln(
						out,
						`boundedProducer := r.StringIn(4096, "cpu-rnm3-pathtrace@3", "cpu-rnm3-pathtrace-atrous-low@3", "cpu-rnm3-pathtrace-atrous-medium@3")`,
					)
					continue
				}
				if fieldKey == "worldlightmap.PrebakeManifest.MaxRayDistance" {
					condition := "boundedProducer"
					if mode != "scan" {
						condition = "boundedOfflineProducer(" + value + ".Producer)"
					}
					fmt.Fprintf(out, "if %s {\n", condition)
					g.emit(out, pkg, field.Type, value+"."+name.Name, fieldKey, mode)
					fmt.Fprintln(out, "}")
					continue
				}
				g.emit(out, pkg, field.Type, value+"."+name.Name, key+"."+name.Name, mode)
			}
		}
	case *ast.Ident:
		name := t.Name
		method := map[string]string{"bool": "Bool", "uint8": "U8", "uint16": "U16", "uint32": "U32", "uint64": "U64", "int": "I32", "int32": "I32", "float32": "F32", "float64": "F64", "string": "String"}[name]
		if method == "" {
			panic(name)
		}
		cast := ""
		if d, ok := g.definitions[key]; ok && d.expr == expr {
			cast = g.typeName(d)
		}
		if name == "string" {
			if mode == "write" {
				fmt.Fprintf(out, "w.String(string(%s),4096)\n", value)
			} else if mode == "read" {
				read := "r.String(4096)"
				if cast != "" {
					read = cast + "(" + read + ")"
				}
				fmt.Fprintf(out, "%s=%s\n", value, read)
			} else {
				fmt.Fprintln(out, "r.SkipString(4096)")
			}
			return
		}
		if mode == "write" {
			if name == "int32" {
				value = "int(" + value + ")"
			}
			fmt.Fprintf(out, "w.%s(%s)\n", method, value)
		} else if mode == "read" {
			read := "r." + method + "()"
			if name == "int32" {
				read = "int32(" + read + ")"
			}
			fmt.Fprintf(out, "%s=%s\n", value, read)
		} else {
			fmt.Fprintf(out, "r.%s()\n", method)
		}
	case *ast.StarExpr:
		_, size := g.dimensions(pkg, t.X)
		if mode == "write" {
			fmt.Fprintf(out, "w.Bool(%s!=nil)\nif %s!=nil{\n", value, value)
			g.emit(out, pkg, t.X, "(*"+value+")", key, mode)
		} else {
			fmt.Fprintln(out, "if r.Bool(){")
			fmt.Fprintf(out, "r.Allocate(%d)\nif r.Err()!=nil{return}\n", size)
			if mode == "read" {
				fmt.Fprintf(out, "%s=new(%s)\n", value, g.exprName(pkg, t.X))
			}
			g.emit(out, pkg, t.X, "(*"+value+")", key, mode)
		}
		fmt.Fprintln(out, "}")
	case *ast.ArrayType:
		index := g.next()
		if t.Len == nil {
			maximum, ok := limits[key]
			if !ok {
				panic("missing slice bound " + key)
			}
			minimum, size := g.dimensions(pkg, t.Elt)
			if mode == "write" {
				fmt.Fprintf(
					out,
					"w.Count(len(%s),%s==nil,%d)\nif w.Err()!=nil{return}\nfor %s:=range %s{\n",
					value,
					value,
					maximum,
					index,
					value,
				)
			} else {
				fmt.Fprintf(out, "n%s,p%s:=r.Count(%d,%d,%d)\nif r.Err()!=nil{return}\n", index, index, maximum, minimum, size)
				if mode == "read" {
					fmt.Fprintf(
						out,
						"if p%s{ %s=make(%s,n%s) }\nfor %s:=range %s{\n",
						index,
						value,
						g.exprName(pkg, t),
						index,
						index,
						value,
					)
				} else {
					fmt.Fprintf(out, "_ = p%s\nfor %s:=0;%s<n%s && r.Err()==nil;%s++{\n", index, index, index, index, index)
				}
			}
		} else {
			if mode == "scan" {
				fmt.Fprintf(out, "for %s:=0;%s<%s;%s++{\n", index, index, t.Len.(*ast.BasicLit).Value, index)
			} else {
				fmt.Fprintf(out, "for %s:=range %s{\n", index, value)
			}
		}
		g.emit(out, pkg, t.Elt, value+"["+index+"]", key, mode)
		fmt.Fprintln(out, "}")
	default:
		panic(fmt.Sprintf("emit %T", expr))
	}
}
